import {readFileSync, writeFileSync, readdirSync, statSync} from 'node:fs';
import {join, relative, extname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {resolveAll, resolvePaths} from './lib/sources.mjs';
import {extractConceptsItems, toSidebarItems} from './lib/subnav.mjs';

function docIds(dir, base) {
  const ids = new Set();
  for (const name of readdirSync(dir)) {
    if (name === '_partials') continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) for (const id of docIds(p, base)) ids.add(id);
    else if (extname(p) === '.mdx') {
      ids.add(relative(base, p).replace(/\.mdx$/, ''));
    }
  }
  return ids;
}

function main() {
  const {section, sidebarId, subnavFile} = resolveAll();
  const {outDocs} = resolvePaths(section);
  const erb = readFileSync(subnavFile, 'utf8');
  // IDs are relative to the docs root, e.g. "concepts/architecture/index"
  const valid = docIds(outDocs, 'docs');
  const items = toSidebarItems(extractConceptsItems(erb), {validId: id => valid.has(id)});
  const sidebar = items.length ? items : [{type: 'autogenerated', dirName: '.'}];

  // Read existing sidebars.js and merge/replace the entry for this sidebarId
  let existing = {};
  try {
    const raw = readFileSync('sidebars.js', 'utf8');
    const match = raw.match(/const sidebars\s*=\s*(\{[\s\S]*\});/);
    if (match) existing = JSON.parse(match[1]);
  } catch { /* first run or unparseable — start fresh */ }

  existing[sidebarId] = sidebar;

  const content = `// @ts-check\n// GENERATED by scripts/gen-sidebar.mjs — do not edit by hand.\n` +
    `/** @type {import('@docusaurus/plugin-content-docs').SidebarsConfig} */\n` +
    `const sidebars = ${JSON.stringify(existing, null, 2)};\n` +
    `export default sidebars;\n`;
  writeFileSync('sidebars.js', content);
  console.log(`[${section}] Wrote sidebar "${sidebarId}" with ${sidebar.length} top-level items into sidebars.js.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
